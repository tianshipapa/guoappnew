export function generateEpisodes(dramaId: string, count: number, dramaTitle: string): Episode[] {
  const episodes: Episode[] = [];
  const titles = [
    '战神归来', '暗夜风云', '家族受辱', '隐藏身份', '谁敢欺她',
    '一怒灭豪门', '医圣显威', '千金倾心', '真假少爷', '风波再起',
    '绝境逢生', '血洗耻辱', '神豪出手', '惊天赌局', '翻云覆雨',
    '强势打脸', '幕后黑手', '霸气宣战', '终极反转', '龙傲九天',
  ];

  for (let i = 1; i <= count; i++) {
    const titleSuffix = titles[(i - 1) % titles.length];
    episodes.push({
      id: `${dramaId}_ep_${i}`,
      number: i,
      title: `第${i}集 ${i <= 3 ? titleSuffix : ''}`.trim(),
      vip: i > 15 && i % 4 === 0,
      duration: 120 + ((i * 17) % 60), // around 2-3 mins typical for short dramas
      vertical: true,
      streamUrl: STREAM_ROUTES[(i - 1) % STREAM_ROUTES.length],
      alternativeRoutes: [
        STREAM_ROUTES[(i - 1) % STREAM_ROUTES.length],
        STREAM_ROUTES[i % STREAM_ROUTES.length],
        STREAM_ROUTES[(i + 1) % STREAM_ROUTES.length],
      ],
    });
  }
  return episodes;
}

